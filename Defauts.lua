local function copy(v)
    if type(v) ~= "table" then return v end
    local t = {}
    for k, x in pairs(v) do t[k] = copy(x) end
    return t
end

-- coordonnee de l ecran de reference -> ecran actuel, par tiers
local function shift(v, ref, cur)
    if v < ref / 3 then return v end
    if v > ref * 2 / 3 then return v + (cur - ref) end
    return v + (cur - ref) / 2
end

local function adapt(t, w, h)
    if t.rel == "BOTTOMLEFT" and type(t.x) == "number" and type(t.y) == "number" then
        t.x = math.floor(shift(t.x, REF_W, w) * 10 + 0.5) / 10
        t.y = math.floor(shift(t.y, REF_H, h) * 10 + 0.5) / 10
    end
    for _, v in pairs(t) do
        if type(v) == "table" then adapt(v, w, h) end
    end
end

local function screen()
    local ok, w, h = pcall(function() return UIParent:GetWidth(), UIParent:GetHeight() end)
    if ok and type(w) == "number" and type(h) == "number" and w > 100 and h > 100 then return w, h end
end

-- copie neuve des reglages par defaut, positions recalees sur l ecran
function ns.DefaultProfile()
    local snap = copy(DATA)
    local w, h = screen()
    if w and (math.abs(w - REF_W) > 1 or math.abs(h - REF_H) > 1) then adapt(snap, w, h) end
    return snap
end
