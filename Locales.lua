-- Langue active : celle choisie par /bf lang, sinon celle du client.
-- Resolue a chaque lecture : Locales.lua est charge avant les
-- SavedVariables, le choix de l utilisateur n est connu qu ensuite.
function ns.ActiveLocale()
    local forced = type(CorpUIDB) == "table" and CorpUIDB.lang
    if forced and locales[forced] then return forced end
    local client = GetLocale and GetLocale() or "enUS"
    if locales[client] then return client end
    return "enUS"
end

function ns.HasLocale(code)
    return locales[code] ~= nil
end

ns.L = setmetatable({}, {
    __index = function(_, key)
        local v = locales[ns.ActiveLocale()][key]
        if v == nil then v = base[key] end
        if v == nil then v = key end
        return v
    end,
})

